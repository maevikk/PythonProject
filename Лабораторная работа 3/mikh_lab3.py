print("Задание 1, Вариант 7")
number_list=[int(x) for x in input("Введите количество элементов последовательности(оканчивающаяся нулем):").split()]
sum=0
count=0
if number_list[-1]==0:
    for x in number_list:
        sum+=x
        count+=1
    print("Сумма чисел последовательности:", sum)
    print("Количество элементов последовательности:",count)
else: print("Ошибка!!! Последний элемент последовательости должен быть нулем")